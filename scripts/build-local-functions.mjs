// Bundles every backend function into Node CommonJS files the bot runs in-process and serves over HTTP,
// so a self-hosted server needs no edge runtime. Run: node scripts/build-local-functions.mjs
import { build } from "esbuild";
import { mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";

// auth-discord runs in the Cloudflare Worker; bot-proxy only exists for cloud-hosted bots.
const SKIP = new Set(["_shared", "bot-proxy", "auth-discord"]);
export const LOCAL_FUNCTIONS = readdirSync("supabase/functions", { withFileTypes: true })
  .filter((d) => d.isDirectory() && !SKIP.has(d.name) && existsSync(`supabase/functions/${d.name}/index.ts`))
  .map((d) => d.name);

const denoShims = {
  name: "deno-shims",
  setup(b) {
    b.onResolve({ filter: /^https:\/\/deno\.land\/std.*\/http\/server\.ts$/ }, () => ({ path: "serve", namespace: "shim" }));
    b.onResolve({ filter: /^https:\/\/deno\.land\/x\/xhr/ }, () => ({ path: "empty", namespace: "shim" }));
    b.onResolve({ filter: /^(https:\/\/esm\.sh\/|npm:)@supabase\/supabase-js/ }, (a) => (
      a.path.endsWith("/cors") ? { path: "cors", namespace: "shim" } : { path: "@supabase/supabase-js", external: true }));
    b.onResolve({ filter: /^npm:zod(@[\d.]+)?$/ }, (a) => b.resolve("zod", { kind: a.kind, resolveDir: process.cwd() }));
    b.onResolve({ filter: /^(https?:|npm:|jsr:)/ }, (a) => { throw new Error(`Unsupported import ${a.path}`); });
    b.onLoad({ filter: /.*/, namespace: "shim" }, (a) => ({
      loader: "js",
      contents: a.path === "serve" ? "export const serve = (h) => globalThis.Deno.serve(h);"
        : a.path === "cors" ? "export const corsHeaders = {'Access-Control-Allow-Origin':'*','Access-Control-Allow-Headers':'authorization, x-client-info, apikey, content-type'};"
        : "",
    }));
  },
};

const OUT = "public/spotbot/local-functions";
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const name of LOCAL_FUNCTIONS) {
  await build({
    entryPoints: [`supabase/functions/${name}/index.ts`],
    outfile: `${OUT}/${name}.cjs`,
    bundle: true, platform: "node", format: "cjs", target: "node20",
    banner: { js: "// GENERATED by scripts/build-local-functions.mjs — edit supabase/functions instead." },
    plugins: [denoShims], logLevel: "warning",
  });
}
console.log(`Bundled ${LOCAL_FUNCTIONS.length} functions: ${LOCAL_FUNCTIONS.join(", ")}`);
