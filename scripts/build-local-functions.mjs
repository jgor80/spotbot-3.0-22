// Bundles the bot-internal backend functions into Node CommonJS files the bot runs in-process,
// so a self-hosted server needs no edge runtime. Run: node scripts/build-local-functions.mjs
import { build } from "esbuild";
import { mkdirSync } from "node:fs";

export const LOCAL_FUNCTIONS = [
  "calculate-ratings", "draft-start", "draft-pick", "draft-result", "draft-confirm-captain",
  "apply-friendly-to-draft", "get-player-profile", "get-leaderboard", "recent-results",
  "mark-attendance", "claim-competition-win", "availability-response",
  "submit-manager-evaluation", "scout-player", "win-probability",
];

const denoShims = {
  name: "deno-shims",
  setup(b) {
    b.onResolve({ filter: /^https:\/\/deno\.land\/std.*\/http\/server\.ts$/ }, () => ({ path: "serve", namespace: "shim" }));
    b.onResolve({ filter: /^https:\/\/deno\.land\/x\/xhr/ }, () => ({ path: "empty", namespace: "shim" }));
    b.onResolve({ filter: /^(https:\/\/esm\.sh\/|npm:)@supabase\/supabase-js/ }, (a) => ({
      path: a.path.endsWith("/cors") ? "cors" : "@supabase/supabase-js",
      ...(a.path.endsWith("/cors") ? { namespace: "shim" } : { external: true }),
    }));
    b.onResolve({ filter: /^(https?:|npm:|jsr:)/ }, (a) => { throw new Error(`Unsupported import ${a.path}`); });
    b.onLoad({ filter: /.*/, namespace: "shim" }, (a) => ({
      loader: "js",
      contents: a.path === "serve" ? "export const serve = (h) => globalThis.Deno.serve(h);"
        : a.path === "cors" ? "export const corsHeaders = {'Access-Control-Allow-Origin':'*','Access-Control-Allow-Headers':'authorization, x-client-info, apikey, content-type'};"
        : "",
    }));
  },
};

mkdirSync("public/spotbot/local-functions", { recursive: true });
for (const name of LOCAL_FUNCTIONS) {
  await build({
    entryPoints: [`supabase/functions/${name}/index.ts`],
    outfile: `public/spotbot/local-functions/${name}.cjs`,
    bundle: true, platform: "node", format: "cjs", target: "node20",
    banner: { js: "// GENERATED by scripts/build-local-functions.mjs — edit supabase/functions instead." },
    plugins: [denoShims], logLevel: "warning",
  });
}
console.log(`Bundled ${LOCAL_FUNCTIONS.length} functions`);
